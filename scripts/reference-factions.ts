// Generates resources/game/engine/reference-factions.ts from the pinned reference
// remake's building definitions for all four civilizations (MIT, see
// third-party/settlers-remake-LICENSE.txt). The Roman table in
// reference-geometry.ts is keyed by engine id and holds only the buildings the
// engine uses; this one holds every definition the reference has, by file name.
// Like that table it is
// reference-remake evidence (class E): it records what the reference defines, not
// what the original executable does, and nothing in the engine reads it yet.
import { resolve } from 'node:path'
import process from 'node:process'
import { parse, type ReferenceGeometry } from './reference-geometry'

const revision = '6ad8c4230a4aa4cd21840f8cb59a38344e41c3e0'
const root = 'jsettlers.common/src/main/resources/jsettlers/common/buildings'
export const CIVILIZATIONS = ['roman', 'egyptian', 'asian', 'amazon'] as const
export type Civilization = typeof CIVILIZATIONS[number]

const get = async (url: string): Promise<Response> => {
  const response = await fetch(url, { signal: AbortSignal.timeout(30_000), headers: { 'User-Agent': 'the-settlers-iii-remake' } })
  if (!response.ok) throw new Error(`Reference source unavailable: ${url} (${response.status})`)
  return response
}

/** Building definition file names of one civilization at the pinned revision, from the revision's own tree. */
export async function definitionFiles(civilization: Civilization): Promise<string[]> {
  const tree = await (await get(`https://api.github.com/repos/paulwedeck/settlers-remake/git/trees/${revision}?recursive=1`)).json() as { tree: { path: string }[], truncated?: boolean }
  if (tree.truncated) throw new Error('The reference tree listing was truncated')
  return tree.tree.map(entry => entry.path).filter(path => path.startsWith(`${root}/${civilization}/`) && path.endsWith('.xml')).map(path => path.slice(`${root}/${civilization}/`.length, -'.xml'.length)).sort()
}

if (import.meta.main) {
  const table: Record<string, Record<string, ReferenceGeometry>> = {}
  for (const civilization of CIVILIZATIONS) {
    table[civilization] = {}
    for (const file of await definitionFiles(civilization)) {
      const bytes = new Uint8Array(await (await get(`https://raw.githubusercontent.com/paulwedeck/settlers-remake/${revision}/${root}/${civilization}/${file}.xml`)).arrayBuffer())
      table[civilization]![file] = parse(file, new TextDecoder().decode(bytes), new Bun.CryptoHasher('sha256').update(bytes).digest('hex'))
    }
  }
  const out = resolve(import.meta.dir, '../resources/game/engine/reference-factions.ts')
  await Bun.write(out, `// Generated by scripts/reference-factions.ts from paulwedeck/settlers-remake@${revision}
// Roman, Egyptian, Asian and Amazon building XML (MIT). Reference-remake evidence, not original observation. Do not edit by hand.
export const REFERENCE_FACTIONS_REVISION = '${revision}'
export const REFERENCE_FACTIONS = ${JSON.stringify(table)} as const
`)
  const check = Bun.spawnSync([process.execPath, 'x', '--bun', 'pickier', 'lint', '--fix', out], { stdout: 'inherit', stderr: 'inherit' })
  console.log(`Wrote reference geometry for ${Object.values(table).reduce((sum, civilization) => sum + Object.keys(civilization).length, 0)} buildings of ${CIVILIZATIONS.length} civilizations${check.exitCode === 0 ? '' : ' (format check reported problems)'}.`)
}
