import type { LandscapeRule } from '../resources/game/engine/rules'
import { resolve } from 'node:path'

export const landscapeRevision = '6ad8c4230a4aa4cd21840f8cb59a38344e41c3e0'
export const landscapeReferencePaths = [
  'jsettlers.logic/src/main/java/jsettlers/logic/map/loading/original/data/OriginalLandscape.java',
  'jsettlers.common/src/main/java/jsettlers/common/landscape/ELandscapeType.java',
  'jsettlers.graphics/src/main/java/jsettlers/graphics/map/draw/Background.java',
  'jsettlers.graphics/src/main/java/jsettlers/graphics/map/draw/ETextureOrientation.java',
  'jsettlers.logic/src/main/java/jsettlers/logic/map/grid/MainGrid.java',
  'jsettlers.common/src/main/java/jsettlers/common/buildings/BuildingVariant.java',
] as const
export function parseLandscapes(original: string, types: string, background: string): LandscapeRule[] {
  const codes = new Map([...original.matchAll(/originalLandscapeType\.put\((\d+), ELandscapeType\.([A-Z_0-9]+)\)/g)].map(m => [m[2]!, Number(m[1])]))
  const positionSource = background.match(/TEXTURE_POSITIONS\s*=\s*\{([\s\S]*?)\n\s*\};/)?.[1]
  if (!positionSource) throw new Error('Reference landscape texture positions are missing')
  const positions = [...positionSource.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/\{\s*(\d+),\s*(\d+),\s*(\d+)\s*\}/g)].map(m => [Number(m[1]), Number(m[2]), Number(m[3])])
  const group = (name: string): string[] => {
    const source = types.match(new RegExp(`\\b${name} = EnumSet\\.of\\(([^)]+)\\)`))?.[1]
    if (!source) throw new Error(`Reference landscape group is missing: ${name}`)
    return source.split(',').map(s => s.trim())
  }
  const groups = { mountain: group('MOUNTAIN_TYPES'), desert: group('DESERT_TYPES'), river: group('RIVERS'), grass: ['GRASS', 'FLATTENED'] }
  const rows = [...types.matchAll(/^\s*([A-Z_0-9]+)\((\d+), new Color\(0xff([a-f0-9]{6})\), (true|false), (true|false)\)/gmi)].map(m => {
    const name = m[1]!, image = Number(m[2]), size = positions[image]?.[2]
    if (!size || size < 1 || size > 5) throw new Error(`Reference material position is missing: ${name}`)
    return { name, image, color: `#${m[3]!.toLowerCase()}`, water: m[4] === 'true', blocking: m[5] === 'true',
      ...(codes.has(name) ? { originalCode: codes.get(name)! } : {}), continuous: size >= 2, period: size >= 2 ? (size - 1) * 32 : 32,
      groups: Object.entries(groups).filter(([, members]) => members.includes(name)).map(([id]) => id) }
  })
  if (rows.length !== 37 || codes.size !== 29 || codes.size !== rows.filter(row => row.originalCode !== undefined).length || new Set(rows.map(row => row.image)).size !== 32) throw new Error('Reference landscape catalog is incomplete')
  return rows
}

if (import.meta.main) {
  const inputs = await Promise.all(landscapeReferencePaths.map(async path => {
    const response = await fetch(`https://raw.githubusercontent.com/paulwedeck/settlers-remake/${landscapeRevision}/${path}`, { signal: AbortSignal.timeout(30_000) })
    if (!response.ok) throw new Error(`Reference unavailable: ${path}`)
    const bytes = new Uint8Array(await response.arrayBuffer())
    return { path, sha256: new Bun.CryptoHasher('sha256').update(bytes).digest('hex'), text: new TextDecoder().decode(bytes) }
  }))
  const rows = parseLandscapes(inputs[0]!.text, inputs[1]!.text, inputs[2]!.text)
  await Bun.write(resolve(import.meta.dir, '../resources/game/engine/reference-landscapes.ts'), `// Generated by scripts/reference-landscapes.ts from paulwedeck/settlers-remake@${landscapeRevision}
// MIT, see third-party/settlers-remake-LICENSE.txt. Reference-remake evidence, not original observation.
export const LANDSCAPE_SOURCES = ${JSON.stringify(inputs.map(({ path, sha256 }) => ({ path, sha256 })), null, 2)} as const
export const REFERENCE_LANDSCAPES = ${JSON.stringify(rows, null, 2)} as const
`)
  console.log(`Generated ${rows.length} landscape types and ${new Set(rows.map(row => row.image)).size} material selectors.`)
}
