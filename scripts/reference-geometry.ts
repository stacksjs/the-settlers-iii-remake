// Generates resources/game/engine/reference-geometry.ts from the pinned reference
// remake's Roman building definitions (MIT, see third-party/settlers-remake-LICENSE.txt).
// The table is reference-remake evidence for footprints, doors and pile positions;
// it is not an original-executable observation.
import { resolve } from 'node:path'
import process from 'node:process'

const revision = '6ad8c4230a4aa4cd21840f8cb59a38344e41c3e0'
const base = `https://raw.githubusercontent.com/paulwedeck/settlers-remake/${revision}/jsettlers.common/src/main/resources/jsettlers/common/buildings/roman`
export const referenceFiles: Record<string, string> = {
  'castle': 'castle', 'storage': 'stock', 'small-residence': 'small_livinghouse', 'medium-residence': 'medium_livinghouse', 'small-tower': 'tower', 'barracks': 'barrack',
  'woodcutter': 'lumberjack', 'forester': 'forester', 'stonecutter': 'stonecutter', 'sawmill': 'sawmill', 'fisher': 'fisher', 'grain-farm': 'farm', 'waterworks': 'waterworks',
  'mill': 'mill', 'bakery': 'baker', 'pig-farm': 'pig_farm', 'slaughterhouse': 'slaughterhouse', 'coal-mine': 'coalmine', 'iron-mine': 'ironmine', 'gold-mine': 'goldmine',
  'iron-smelter': 'ironmelt', 'gold-smelter': 'goldmelt', 'toolsmith': 'toolsmith', 'weaponsmith': 'weaponsmith',
  'winery': 'winegrower', 'charcoal-maker': 'charcoal_burner', 'small-temple': 'temple', 'large-temple': 'big_temple', 'healers-hut': 'hospital',
  'large-tower': 'big_tower', 'lookout-tower': 'lookout_tower', 'large-residence': 'big_livinghouse',
}
// Reference material names mapped to engine goods; NO_MATERIAL marks a storage pile.
const materials: Record<string, string> = {
  TRUNK: 'log', PLANK: 'plank', STONE: 'stone', CROP: 'grain', FLOUR: 'flour', WATER: 'water', BREAD: 'bread', PIG: 'pig', MEAT: 'meat', FISH: 'fish', COAL: 'coal', IRONORE: 'ironore',
  GOLDORE: 'goldore', IRON: 'iron', GOLD: 'gold', HAMMER: 'hammer', BLADE: 'shovel', AXE: 'axe', SAW: 'saw', PICK: 'pickaxe', SCYTHE: 'scythe', FISHINGROD: 'fishingrod', SWORD: 'sword', SPEAR: 'spear', BOW: 'bow', WINE: 'wine', NO_MATERIAL: '*',
}

type Attrs = Record<string, string>
const elements = (xml: string, tag: string): Attrs[] => [...xml.matchAll(new RegExp(`<${tag}\\s+([^>]*?)/?>`, 'g'))].map(m => Object.fromEntries([...m[1]!.matchAll(/(\w+)="([^"]*)"/g)].map(a => [a[1]!, a[2]!])))
const offset = (a: Attrs): [number, number] => {
  const dx = Number(a.dx), dy = Number(a.dy)
  if (!Number.isInteger(dx) || !Number.isInteger(dy) || Math.abs(dx) > 20 || Math.abs(dy) > 20) throw new Error(`Invalid offset ${JSON.stringify(a)}`)
  return [dx, dy]
}

export interface ReferenceGeometry {
  file: string, sha256: string, blocked: [number, number][], protected: [number, number][], door: [number, number]
  construction: { good: string, at: [number, number], required: number }[]
  piles: { good: string, at: [number, number], role: 'request' | 'offer' }[]
  builders: [number, number][], ground: string[], mine: boolean
}

export function parse(file: string, xml: string, sha256: string): ReferenceGeometry {
  const blocked = elements(xml, 'blocked'), door = elements(xml, 'door')[0]
  if (!door) throw new Error(`${file} has no door`)
  // Materials outside the Roman engine catalog (weapons for later military work) keep their reference name.
  const good = (name: string | undefined): string => { if (!name) throw new Error(`${file} has a pile without material`); return materials[name] ?? `reference:${name}` }
  return {
    file, sha256,
    blocked: blocked.filter(a => a.block !== 'false').map(offset),
    protected: blocked.filter(a => a.block === 'false').map(offset),
    door: offset(door),
    construction: elements(xml, 'constructionStack').map(a => ({ good: good(a.material), at: offset(a), required: Number(a.buildrequired) })),
    piles: [...elements(xml, 'requestStack').map(a => ({ good: good(a.material), at: offset(a), role: 'request' as const })), ...elements(xml, 'offerStack').map(a => ({ good: good(a.material), at: offset(a), role: 'offer' as const }))],
    builders: elements(xml, 'bricklayer').map(offset),
    ground: [...new Set(elements(xml, 'ground').map(a => a.groundtype!))],
    mine: /<building[^>]*\smine="true"/.test(xml),
  }
}

if (import.meta.main) {
  const table: Record<string, ReferenceGeometry> = {}
  for (const [id, file] of Object.entries(referenceFiles)) {
    const response = await fetch(`${base}/${file}.xml`, { signal: AbortSignal.timeout(30_000) })
    if (!response.ok) throw new Error(`Reference definition unavailable: ${file}`)
    const bytes = new Uint8Array(await response.arrayBuffer())
    table[id] = parse(file, new TextDecoder().decode(bytes), new Bun.CryptoHasher('sha256').update(bytes).digest('hex'))
  }
  const out = resolve(import.meta.dir, '../resources/game/engine/reference-geometry.ts')
  await Bun.write(out, `// Generated by scripts/reference-geometry.ts from paulwedeck/settlers-remake@${revision}
// Roman building XML (MIT). Reference-remake evidence, not original observation. Do not edit by hand.
export const REFERENCE_REVISION = '${revision}'
export const REFERENCE_GEOMETRY = ${JSON.stringify(table)} as const
`)
  const check = Bun.spawnSync([process.execPath, 'x', '--bun', 'pickier', 'lint', '--fix', out], { stdout: 'inherit', stderr: 'inherit' })
  console.log(`Wrote reference geometry for ${Object.keys(table).length} Roman buildings${check.exitCode === 0 ? '' : ' (format check reported problems)'}.`)
}
